"""Generate RGB565 theme and enforce contrast on quantized colours, no network."""
from pathlib import Path
import json, re
r = Path(__file__).resolve().parents[2]
source = Path(__file__).with_name('av-tokens.css').read_text()
revision = 'bb279c5d689b3be85044b75e7558d7863b6045d3'
tokens = dict(re.findall(r'--([\w-]+):\s*(#[0-9a-fA-F]{6});', source))
names = {'BG':'surface','CELL':'surface-raised','CELL_HOT':'surface-disabled',
 'CELL_DOWN':'border','OUTLINE':'border-strong','TITLE':'text-secondary','ICON':'text',
 'NAV':'accent','VALUE':'text','UNIT':'text-secondary','ACCENT':'accent','TRACK':'surface-sunken',
 'DIM':'text-secondary','DISABLED':'text-faint','TOGGLE_ON':'accent-live','ALERT':'warn-soft-text',
 'LINK':'text-muted','LIVE':'accent-live','DANGER':'danger','STOP':'danger-strong','INDICATOR':'text-muted'}
def rgb565(s):
    v=int(s[1:],16); return ((v>>19)<<11)|(((v>>10)&63)<<5)|((v>>3)&31)
def rgb(c): return [(c>>11)/31, ((c>>5)&63)/63, (c&31)/31]
def luminance(c):
    v=[x/12.92 if x<=.04045 else ((x+.055)/1.055)**2.4 for x in rgb(c)]
    return sum(x*w for x,w in zip(v,[.2126,.7152,.0722]))
def contrast(a,b):
    hi,lo=sorted([luminance(a),luminance(b)],reverse=True); return (hi+.05)/(lo+.05)
colours={k:rgb565(tokens[v]) for k,v in names.items()}
# Dark danger plate derived from --danger at 36% over --surface; white text remains readable.
colours['STOP'] = rgb565('#652529')
checks=[]
for fg,minimum in [('VALUE',7),('TITLE',4.5),('UNIT',4.5),('ACCENT',3),('LIVE',4.5),('ALERT',4.5),('INDICATOR',3)]:
    for bg in ['BG','CELL','CELL_HOT','CELL_DOWN']:
        ratio=contrast(colours[fg],colours[bg]); assert ratio>=minimum,(fg,bg,ratio)
        checks.append(dict(fg=fg,bg=bg,minimum=minimum,ratio=round(ratio,3)))
for bg in ['TOGGLE_ON','STOP']:
    fg='BG' if bg=='TOGGLE_ON' else 'VALUE'
    ratio=contrast(colours[fg],colours[bg]); assert ratio>=4.5,(fg,bg,ratio)
    checks.append(dict(fg=fg,bg=bg,minimum=4.5,ratio=round(ratio,3)))
# Precision-editor trailing zeroes use C_DIM; unselected real digits use 88% C_VALUE.
# These are numeric ink too, even though their emphasis differs from the held digit.
dimmed = (((colours['VALUE']>>11)&31)*88//100<<11) | (((colours['VALUE']>>5)&63)*88//100<<5) | ((colours['VALUE']&31)*88//100)
for name,c in [('DIM',colours['DIM']),('VALUE_88_PERCENT',dimmed)]:
    for bg in ['BG','CELL_HOT']:
        ratio=contrast(c,colours[bg]);assert ratio>=7,(name,bg,ratio)
        checks.append(dict(fg=name,bg=bg,minimum=7,ratio=round(ratio,3)))
header='/* Generated by tools/graphics/make-palette.py from av-frameworks '+revision+'. */\n#ifndef ELECTRA_THEME_H\n#define ELECTRA_THEME_H\n'
header+='/* C_STOP overrides the source danger token with #652529 for readable white labels. */\n'
header+=''.join(f'#define C_{k:<12} 0x{v:04X}u /* --{names[k]} {tokens[names[k]]} */\n' for k,v in colours.items())
header+='#endif\n'; (r/'src/app/theme.h').write_text(header)
(Path(__file__).with_name('contrast.json')).write_text(json.dumps(dict(source_revision=revision,colours=colours,checks=checks),indent=2)+'\n')
print(f'{len(checks)} quantized contrast checks passed')
